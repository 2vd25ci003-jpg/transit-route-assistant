"""End-to-end benchmark runner for TransitAI.

Measures and writes real benchmark metrics to ml/results.md and ml/results.json:
1. Forecast MAE/RMSE vs previous-week naive baseline (reuses existing ml/results.md)
2. Fleet dispatch optimizer total distance vs nearest-neighbor baseline
3. Simulated headway variance with and without holding strategy (5 seeds)
4. p95 latency of GET /routes/search

Note: All measurements use synthetic data generated by data/generate.py and
simulated bus runs.

Usage:
    backend/venv/Scripts/python.exe scripts/benchmark.py
"""

from __future__ import annotations

import json
import os
import re
import sys
import time
from datetime import datetime, timezone
from pathlib import Path

import numpy as np
from fastapi.testclient import TestClient

PROJECT_ROOT = Path(__file__).resolve().parent.parent
BACKEND_DIR = PROJECT_ROOT / "backend"
ML_DIR = PROJECT_ROOT / "ml"
RESULTS_MD = ML_DIR / "results.md"
RESULTS_JSON = ML_DIR / "results.json"

sys.path.insert(0, str(PROJECT_ROOT))
sys.path.insert(0, str(BACKEND_DIR))
os.chdir(BACKEND_DIR)

from app.database import SessionLocal  # noqa: E402
from app.main import app  # noqa: E402
from app.models import Stop  # noqa: E402
from app.services.simulator import (  # noqa: E402
    load_route_geometries,
    run_bunching_experiment,
)
from ml.optimizer import StopPoint, optimize_dispatch  # noqa: E402


def _read_existing_forecast_metrics() -> dict:
    """Parse existing forecast MAE/RMSE from ml/results.md, or train if absent."""
    if RESULTS_MD.exists():
        text = RESULTS_MD.read_text(encoding="utf-8")
        # Look for Test Metrics table rows
        base_m = re.search(
            r"\| Naive Baseline \(Prev Week\) \|\s*([\d.]+)\s*\|\s*([\d.]+)\s*\|",
            text.split("## Test Metrics")[-1] if "## Test Metrics" in text else text,
        )
        rf_m = re.search(
            r"\| Random Forest \|\s*([\d.]+)\s*\|\s*([\d.]+)\s*\|",
            text.split("## Test Metrics")[-1] if "## Test Metrics" in text else text,
        )
        if base_m and rf_m:
            base_mae = float(base_m.group(1))
            base_rmse = float(base_m.group(2))
            rf_mae = float(rf_m.group(1))
            rf_rmse = float(rf_m.group(2))
            mae_imp = round(((base_mae - rf_mae) / base_mae) * 100.0, 1)
            rmse_imp = round(((base_rmse - rf_rmse) / base_rmse) * 100.0, 1)
            return {
                "baseline_mae": base_mae,
                "baseline_rmse": base_rmse,
                "rf_mae": rf_mae,
                "rf_rmse": rf_rmse,
                "mae_improvement_pct": mae_imp,
                "rmse_improvement_pct": rmse_imp,
            }

    from ml.train_forecast import train_and_evaluate

    res = train_and_evaluate()
    base_mae = round(res["base_test_mae"], 2)
    base_rmse = round(res["base_test_rmse"], 2)
    rf_mae = round(res["test_mae"], 2)
    rf_rmse = round(res["test_rmse"], 2)
    return {
        "baseline_mae": base_mae,
        "baseline_rmse": base_rmse,
        "rf_mae": rf_mae,
        "rf_rmse": rf_rmse,
        "mae_improvement_pct": round(((base_mae - rf_mae) / base_mae) * 100.0, 1),
        "rmse_improvement_pct": round(((base_rmse - rf_rmse) / base_rmse) * 100.0, 1),
    }


def _benchmark_optimizer(db) -> list[dict]:
    """Compare OR-Tools vs Nearest-Neighbor baseline on all DB stops."""
    stops = db.query(Stop).order_by(Stop.id).all()
    points = [StopPoint(s.id, s.name, s.lat, s.lng) for s in stops]
    results = []
    for fleet_size in (2, 3, 4):
        res = optimize_dispatch(points, fleet_size=fleet_size, depot_stop_id=points[0].id)
        results.append({
            "fleet_size": fleet_size,
            "num_stops": len(points),
            "ortools_km": res["total_distance_km"],
            "baseline_km": res["baseline_distance_km"],
            "savings_pct": res["savings_pct"],
        })
    return results


def _benchmark_route_search_latency(db) -> dict:
    """Measure p50 and p95 latency (ms) of GET /routes/search across stop pairs."""
    stop_ids = [s.id for s in db.query(Stop).order_by(Stop.id).all()]
    pairs = [
        (stop_ids[i], stop_ids[j])
        for i in range(len(stop_ids))
        for j in range(len(stop_ids))
        if i != j
    ][:60]

    latencies_ms: list[float] = []
    with TestClient(app) as client:
        # Warmup
        client.get("/routes/search", params={"from": pairs[0][0], "to": pairs[0][1]})
        for from_id, to_id in pairs:
            t0 = time.perf_counter()
            resp = client.get(
                "/routes/search", params={"from": from_id, "to": to_id}
            )
            elapsed_ms = (time.perf_counter() - t0) * 1000.0
            if resp.status_code == 200:
                latencies_ms.append(elapsed_ms)

    p50 = float(np.percentile(latencies_ms, 50))
    p95 = float(np.percentile(latencies_ms, 95))
    max_ms = float(max(latencies_ms))
    return {
        "samples": len(latencies_ms),
        "p50_ms": round(p50, 2),
        "p95_ms": round(p95, 2),
        "max_ms": round(max_ms, 2),
        "under_1s": p95 < 1000.0,
    }


def main() -> None:
    db = SessionLocal()
    try:
        forecast = _read_existing_forecast_metrics()
        optimizer_runs = _benchmark_optimizer(db)
        geometries = load_route_geometries(db)
        bunching = run_bunching_experiment(geometries)
        latency = _benchmark_route_search_latency(db)
    finally:
        db.close()

    generated_at = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    payload = {
        "generated_at": generated_at,
        "synthetic_data_note": "All metrics are measured on synthetic Hubli-Dharwad data (data/generate.py) and simulated bus runs.",
        "forecast": forecast,
        "optimizer": optimizer_runs,
        "bunching": bunching,
        "route_search_latency": latency,
    }

    ML_DIR.mkdir(parents=True, exist_ok=True)
    RESULTS_JSON.write_text(json.dumps(payload, indent=2), encoding="utf-8")

    opt_rows = "\n".join(
        f"| {r['fleet_size']} buses ({r['num_stops']} stops) | {r['baseline_km']} km | {r['ortools_km']} km | {r['savings_pct']:+.2f}% |"
        for r in optimizer_runs
    )

    md = f"""# TransitAI Benchmark Results

> **Note**: All metrics below are measured from real runs on **synthetic Hubli-Dharwad data** (`data/generate.py`) and **simulated** bus operations. Generated: `{generated_at}`.

## 1. Demand Forecast (Random Forest vs Previous-Week Baseline)
| Model | Test MAE | Test RMSE |
| :--- | ---: | ---: |
| Naive Baseline (Prev Week) | {forecast['baseline_mae']:.2f} | {forecast['baseline_rmse']:.2f} |
| Random Forest | {forecast['rf_mae']:.2f} | {forecast['rf_rmse']:.2f} |

- **MAE improvement**: `+{forecast['mae_improvement_pct']}%`
- **RMSE improvement**: `+{forecast['rmse_improvement_pct']}%`

## 2. Fleet Dispatch Optimizer (OR-Tools vs Nearest-Neighbor Baseline)
| Instance | Nearest-Neighbor Baseline | OR-Tools Distance | Savings |
| :--- | ---: | ---: | ---: |
{opt_rows}

## 3. Bus Bunching & Holding Strategy (Simulated, 5 Seeds: {bunching['seeds']})
| Mode | Headway Mean (min) | Headway StdDev (min) | Bunching Events (<4m) |
| :--- | ---: | ---: | ---: |
| Without Holding (Simulated) | {bunching['without_holding']['headway_mean_min']} | {bunching['without_holding']['headway_std_min']} | {bunching['without_holding']['bunching_count']} |
| With Holding (Simulated) | {bunching['with_holding']['headway_mean_min']} | {bunching['with_holding']['headway_std_min']} | {bunching['with_holding']['bunching_count']} |

- **Headway StdDev reduction**: `{bunching['std_reduction_pct']}%`

## 4. `/routes/search` Latency ({latency['samples']} stop-pair queries)
- **p50 latency**: `{latency['p50_ms']} ms`
- **p95 latency**: `{latency['p95_ms']} ms` (Target: `< 1000 ms` — **{'PASS' if latency['under_1s'] else 'FAIL'}**)
- **Max latency**: `{latency['max_ms']} ms`
"""
    RESULTS_MD.write_text(md, encoding="utf-8")
    print(md)


if __name__ == "__main__":
    main()
